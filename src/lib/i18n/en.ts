/** Every leaf is a string; the English file fixes which keys exist. */
export interface Messages {
  readonly [key: string]: string | Messages;
}

/** The same keys as `T` with any string at each leaf: what a translation is. */
export type Catalog<T> = {
  readonly [K in keyof T]: T[K] extends string ? string : Catalog<T[K]>;
};
